package license

import (
	"crypto/ed25519"
	"encoding/base64"
	"fmt"
	"strings"

	"github.com/weaviate/weaviate/usecases/license/protocol"
)

// embeddedServerKeys are the license service's signing keys this build
// trusts, as key id -> base64url public key. Keep the current and the
// previous key so a server-side rotation does not break older binaries.
//
// The production key is generated by the license service's Terraform; paste
// the "server_public_key" output here. Until then only LICENSE_SERVER_KEYS
// can supply keys, which is intended for development.
var embeddedServerKeys = map[string]string{
	// "srv-2026-09": "…",
}

// TrustedServerKeys merges the embedded keys with cfg.ServerKeys.
func TrustedServerKeys(cfg Config) (protocol.ServerKeySet, error) {
	set := protocol.ServerKeySet{}
	for id, b64 := range embeddedServerKeys {
		pub, err := base64.RawURLEncoding.DecodeString(b64)
		if err != nil || len(pub) != ed25519.PublicKeySize {
			return nil, fmt.Errorf("license: embedded server key %q is malformed", id)
		}
		set[id] = ed25519.PublicKey(pub)
	}
	for _, entry := range cfg.ServerKeys {
		id, b64, ok := strings.Cut(entry, ":")
		if !ok || id == "" {
			return nil, fmt.Errorf("license: %s entry %q must be id:base64url", EnvServerKeys, entry)
		}
		pub, err := base64.RawURLEncoding.DecodeString(b64)
		if err != nil || len(pub) != ed25519.PublicKeySize {
			return nil, fmt.Errorf("license: %s entry %q has a malformed public key", EnvServerKeys, id)
		}
		set[id] = ed25519.PublicKey(pub)
	}
	return set, nil
}
